# scripts/seed_demo_data.py
#
# Sprint 5, roadmap item 1: "Prepare Demo Mode - a small prepared local dataset and
# offline-safe demo path for the live presentation."
#
# Run this once before presenting:
#
#     python scripts/seed_demo_data.py
#
# What it does: logs into the REAL database (database/researchlens.db, the same one
# `python app.py` uses) through the app's own service-layer functions - the exact same
# functions routes/papers_routes.py calls - and creates one fully-populated demo
# account. It is safe to run more than once: it looks for the demo account by email
# first and deletes any previous demo project before recreating it fresh, so re-running
# this always leaves you with exactly one clean, presentable demo project, never a pile
# of duplicates from earlier rehearsals.
#
# WHY this is "offline-safe": every AI Summary, Literature Matrix field, Paper
# Synthesis, and Ask the Literature answer below is written out by hand, in this
# script, as plain Python strings - not generated by actually calling OpenAI. Logging
# in as the demo account and clicking through the app therefore needs ZERO network
# calls for the core walkthrough (dashboard -> project -> paper detail -> matrix ->
# synthesis -> chat) - nothing depends on the presentation room's WiFi, a live OpenAI
# key, or Semantic Scholar/OpenAlex being reachable at exactly the wrong moment.
#
# Two papers (Okafor and Dubois, below) are left with no Matrix fields filled in on
# purpose, exactly as a freshly-saved paper would look - so if the room's WiFi *does*
# cooperate and OPENAI_API_KEY is set, you can still click "Extract with AI" on one of
# them live, as a bonus, without that being a dependency of the core demo.
#
# This reuses the same "Generative AI in Higher Education" project and the same five
# papers as the README's own screenshots, so every artifact produced for this project -
# the README, the Sprint slide decks, and this live demo - tells one consistent story.

import os
import sys
from datetime import datetime

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from services.database_service import get_session, init_db
from services.auth_service import get_user_by_email, create_user, hash_password, delete_user
from services.project_service import (
    create_project,
    get_projects_for_user,
    delete_project,
    set_project_synthesis,
)
from services.paper_service import (
    create_paper_from_search_result,
    save_paper_to_project,
    set_paper_matrix_fields,
    set_paper_summary,
    set_saved_paper_relevance,
    get_saved_paper,
)
from services.literature_chat_service import add_chat_message

DEMO_EMAIL = "demo@researchlens.ai"
DEMO_PASSWORD = "DemoDay2026!"
DEMO_NAME = "Demo Presenter"


def _wipe_existing_demo_account(session):
    """If a previous run (or a previous rehearsal) left a demo account behind, remove
    it completely first - delete_project() already cascades to that project's saved
    papers, chat messages, etc., so this is enough to leave a clean slate."""
    existing = get_user_by_email(session, DEMO_EMAIL)
    if existing is None:
        return
    for project in get_projects_for_user(session, existing.id):
        delete_project(session, project)
    delete_user(session, existing)


def seed():
    init_db()
    session = get_session()
    try:
        _wipe_existing_demo_account(session)

        user = create_user(session, name=DEMO_NAME, email=DEMO_EMAIL,
                            password_hash=hash_password(DEMO_PASSWORD))

        project = create_project(
            session, user_id=user.id,
            title="Generative AI in Higher Education",
            research_question="How is generative AI being adopted and governed in university teaching and learning?",
            research_field="Education Technology",
            keywords="ChatGPT, generative AI, higher education, academic policy",
        )

        # --- Five papers, the same set used across this project's own README --------
        # screenshots. Two (Okafor, Dubois) are left without Matrix fields on purpose -
        # see the file-level comment above.

        chan = create_paper_from_search_result(session, {
            "title": "ChatGPT and AI-Generated Content in Higher Education: Opportunities and Challenges",
            "authors": "Cecilia Chan, Wenjie Hu", "year": 2023, "source": "semantic_scholar",
            "abstract": (
                "This study examines how generative AI tools such as ChatGPT are reshaping teaching and "
                "learning in universities, surveying 400 students and faculty across six institutions on "
                "adoption patterns, perceived benefits, and concerns around academic integrity."
            ),
            "doi": "10.9999/demo-chan-2023",
        })
        schwarz = create_paper_from_search_result(session, {
            "title": "Does ChatGPT Enhance Student Learning in Statistics Education?",
            "authors": "Nadja Schwarz", "year": 2025, "source": "openalex",
            "abstract": (
                "An experimental study comparing statistics students who used ChatGPT for guided practice "
                "against a control group, measuring conceptual understanding, procedural fluency, and "
                "reliance on AI-generated code."
            ),
            "doi": "10.9999/demo-schwarz-2025",
        })
        okafor = create_paper_from_search_result(session, {
            "title": "Generative AI Adoption Among University Faculty: A Mixed-Methods Study",
            "authors": "Ngozi Okafor, Erik Lindqvist", "year": 2024, "source": "semantic_scholar",
            "abstract": (
                "Explores how faculty across disciplines are adopting (or resisting) generative AI tools in "
                "course design, assessment, and research, and what institutional support would change that "
                "calculus."
            ),
            "doi": "10.9999/demo-okafor-2024",
        })
        park = create_paper_from_search_result(session, {
            "title": "Academic Integrity in the Age of Large Language Models",
            "authors": "Soo-ah Park, Kwame Mensah, Elena Ruiz", "year": 2024, "source": "openalex",
            "abstract": (
                "Reviews how universities are redefining plagiarism and academic misconduct policy in "
                "response to large language models, proposing a framework for disclosure-based assessment "
                "design."
            ),
            "doi": "10.9999/demo-park-2024",
        })
        dubois = create_paper_from_search_result(session, {
            "title": "Institutional Policy Responses to Generative AI: A Comparative Analysis",
            "authors": "Camille Dubois", "year": 2025, "source": "semantic_scholar",
            "abstract": (
                "A comparative policy analysis across 12 universities in Europe and North America, tracking "
                "how institutional guidance on generative AI evolved between 2023 and 2025."
            ),
            "doi": "10.9999/demo-dubois-2025",
        })

        for paper in (chan, schwarz, okafor, park, dubois):
            save_paper_to_project(session, project.id, paper.id)

        # --- Literature Matrix: filled in for three papers, left blank for two -------

        set_paper_matrix_fields(
            session, chan,
            methodology="Mixed-methods: cross-institutional survey (n=400) plus 22 semi-structured interviews with faculty and students.",
            sample="400 survey respondents and 22 interview participants across six universities in three countries.",
            findings="Widespread informal adoption for brainstorming and writing support; faculty policy lagged far behind student usage.",
            limitations="Self-selected sample likely skews toward early AI adopters; no longitudinal follow-up.",
        )
        set_paper_matrix_fields(
            session, schwarz,
            methodology="Randomized controlled trial across two sections of an introductory statistics course (n=140).",
            sample="140 undergraduate students enrolled in an introductory statistics course.",
            findings="ChatGPT only partly follows standard statistical procedure; gains concentrated in procedural fluency, not conceptual understanding.",
            limitations="Single institution; one semester; results may not generalize to graduate-level statistics.",
        )
        set_paper_matrix_fields(
            session, park,
            methodology="Policy document analysis across 48 universities, supplemented by a Delphi panel of 15 academic integrity officers.",
            sample="48 institutional policy documents; 15 expert panelists.",
            findings="Most policies still frame AI use as binary permitted/forbidden rather than disclosure-based, creating enforcement gaps.",
            limitations="Policy text analysis does not capture actual enforcement practice or informal norms.",
        )
        # okafor and dubois: deliberately left un-extracted - see file-level comment.

        # --- AI Summary + its evidence, pre-written for one paper (Chan) -------------
        # Six paragraphs, matching the exact fixed shape stream_summarize_paper() asks
        # the real AI for - so the demo page looks indistinguishable from a live-
        # generated one, with its own verified/unverified evidence chips.

        chan_summary = (
            "Chan and Hu (2023) investigate how generative AI tools such as ChatGPT are reshaping teaching "
            "and learning in universities, surveying adoption patterns, perceived benefits, and concerns "
            "around academic integrity across six institutions.\n\n"
            "Existing research on AI in education had largely relied on isolated case studies; this study "
            "instead sought a broader, cross-institutional picture of how students and faculty are actually "
            "using generative AI day to day, rather than how policy assumes they are.\n\n"
            "The authors combined a cross-institutional survey of 400 students and faculty with 22 "
            "semi-structured interviews, deliberately pairing breadth with depth across six universities in "
            "three countries.\n\n"
            "Adoption was widespread but informal: students and faculty reported using ChatGPT for "
            "brainstorming and writing support well before institutional policy caught up, with usage "
            "patterns consistently outpacing any formal guidance.\n\n"
            "The authors conclude that institutions need to move from reactive, binary AI policies toward "
            "structured guidance that acknowledges how embedded these tools already are in everyday academic "
            "work.\n\n"
            "A notable limitation is the self-selected nature of the sample, which likely skews toward "
            "respondents already comfortable with AI tools, and the absence of any longitudinal follow-up to "
            "see whether usage patterns persist or evolve."
        )
        set_paper_summary(session, chan, chan_summary, evidence={
            "3": {"quote": "surveying 400 students and faculty across six institutions", "verified": True},
            "4": {"quote": "faculty policy has not kept pace with how widely students already rely on these tools", "verified": False},
        })

        # --- Relevance analysis, pre-written for two of the saved papers -------------

        chan_saved = get_saved_paper(session, project.id, chan.id)
        set_saved_paper_relevance(session, chan_saved, (
            "Highly relevant: this paper's cross-institutional adoption data directly informs the project's "
            "research question about how generative AI is being adopted in practice, and its finding that "
            "policy lags adoption motivates the governance half of the question. Relevance: 5/5"
        ))
        schwarz_saved = get_saved_paper(session, project.id, schwarz.id)
        set_saved_paper_relevance(session, schwarz_saved, (
            "Relevant as a concrete case study: it narrows the project's broad question down to one "
            "discipline (statistics) and one outcome (learning gains), showing what 'adoption' looks like in "
            "a single classroom rather than only at the policy level. Relevance: 4/5"
        ))

        # --- Paper Synthesis across three of the five papers, with its evidence ------

        synthesis_text = (
            "Across the saved literature, generative AI adoption in higher education is running well ahead "
            "of institutional policy. Students and faculty report using tools like ChatGPT informally for "
            "brainstorming, drafting, and statistical code generation, but most universities still frame "
            "that use in binary permitted-or-forbidden terms rather than a disclosure-based model.\n\n"
            "Learning outcomes are mixed and task-dependent: gains concentrate in procedural fluency rather "
            "than conceptual understanding, and ChatGPT only partly follows standard statistical procedure "
            "on its own, suggesting these tools work best as a scaffold with human oversight rather than a "
            "substitute for it.\n\n"
            "Policy responses so far lag the pace of adoption and vary widely by institution, with "
            "disclosure-based assessment design proposed as a more enforceable middle ground than outright "
            "bans."
        )
        set_project_synthesis(
            session, project, synthesis_text, [chan.id, schwarz.id, park.id],
            evidence=[
                {"paper_id": schwarz.id, "label": "Schwarz (2025)",
                 "quote": "ChatGPT only partly follows standard statistical procedure", "verified": True},
                {"paper_id": park.id, "label": "Park, Mensah, and Ruiz (2024)",
                 "quote": "Most policies still frame AI use as binary permitted/forbidden rather than disclosure-based",
                 "verified": True},
                {"paper_id": chan.id, "label": "Chan and Hu (2023)",
                 "quote": "faculty policy has not kept pace with how widely students already rely on these tools",
                 "verified": False},
            ],
        )

        # --- Ask the Literature: a two-turn conversation already in the thread -------

        add_chat_message(
            session, project.id, "user",
            "What does the literature say about using ChatGPT for teaching statistics, and is it actually effective?",
        )
        add_chat_message(
            session, project.id, "assistant",
            (
                "The evidence is mixed. In statistics education specifically, ChatGPT can help generate code "
                "and facilitate data analysis, including for students with limited statistical background, "
                "but it only partly follows standard statistical procedure on its own.\n\n"
                "Because of that gap, the literature recommends universities emphasize conceptual "
                "understanding rather than software-specific skills when integrating it into coursework, and "
                "pair any AI-assisted practice with human oversight rather than treating it as a stand-in for "
                "instruction."
            ),
            evidence=[
                {"paper_id": schwarz.id, "label": "Schwarz (2025)",
                 "quote": "ChatGPT only partly follows standard statistical procedure", "verified": True},
                {"paper_id": schwarz.id, "label": "Schwarz (2025)",
                 "quote": "gains concentrated in procedural fluency, not conceptual understanding", "verified": True},
            ],
        )

        print("Demo account ready.")
        print(f"  Email:    {DEMO_EMAIL}")
        print(f"  Password: {DEMO_PASSWORD}")
        print(f"  Project:  {project.title!r} ({len(get_projects_for_user(session, user.id))} project, 5 saved papers)")
    finally:
        session.close()


if __name__ == "__main__":
    seed()
